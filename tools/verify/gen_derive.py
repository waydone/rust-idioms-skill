"""Build the proc-macro crate from the derive skeleton in references/macros.md.

usage: python3 -I gen_derive.py <skill_dir> <hello-derive/src/lib.rs>

A proc-macro needs its own `proc-macro = true` crate, so gen_harness.py skips these blocks.
This takes the block with `#[proc_macro_derive(Hello)]` verbatim and splices the
"spanned error" block (`syn::Data::Union(_)`) into `expand`, right after `let name = ...;`,
which is where the page says it belongs. tests/derive.rs then uses the derive for real.
"""
import pathlib
import re
import sys

text = (pathlib.Path(sys.argv[1]) / "references" / "macros.md").read_text(encoding="utf-8")
blocks = re.findall(r"```rust\n(.*?)```", text, re.S)


def find(marker: str) -> str:
    hits = [b for b in blocks if marker in b]
    if len(hits) != 1:
        sys.exit(f"gen_derive: expected exactly one rust block containing {marker!r}, found {len(hits)}")
    return hits[0]


skeleton, guard = find("#[proc_macro_derive(Hello)]"), find("syn::Data::Union(_)")
anchor = "    let name = &input.ident;\n"
if skeleton.count(anchor) != 1:
    sys.exit("gen_derive: anchor `let name = &input.ident;` not found in the derive skeleton")
guard = "".join("    " + line + "\n" for line in guard.rstrip("\n").split("\n"))
out = pathlib.Path(sys.argv[2])
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("// generated by gen_derive.py from references/macros.md\n" + skeleton.replace(anchor, anchor + guard), encoding="utf-8")
print(f"derive crate: {out.parent.parent.name}/src/lib.rs written")
